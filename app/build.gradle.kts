import java.util.Properties

// Release signing: keystore.properties is created by build_loom.bat on first run (never commit it).
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("org.jetbrains.kotlin.plugin.compose")
}

android {
    namespace = "com.loom.runtime"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.loom.runtime"
        minSdk = 30 // PowerManager.getThermalHeadroom() needs API 30
        targetSdk = 35
        versionCode = 2
        versionName = "0.2.0"
        // The iQOO 15 is arm64; shipping only arm64 native libs cuts the APK size a lot.
        ndk { abiFilters += listOf("arm64-v8a") }
    }

    signingConfigs {
        create("release") {
            if (keystoreProps.isNotEmpty()) {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            isDebuggable = false
            if (keystoreProps.isNotEmpty()) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
    }

    // MediaPipe memory-maps model files; they must be stored uncompressed in the APK.
    androidResources {
        noCompress += listOf("tflite", "task")
    }
}

